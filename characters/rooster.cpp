
#include "rooster.h"
#include "primitives.h"

void drawRooster(float x, float y, float z, float scale)
{
    glPushMatrix();

    glTranslatef(x, y, z);
    glScalef(scale, scale, scale);

    // Main body
    drawSphere(0, 0.48, 0, 0.38, 0.30, 0.25,
               0.65, 0.22, 0.08);

    // Chest
    drawSphere(0.18, 0.55, 0.08, 0.22, 0.25, 0.20,
               0.85, 0.38, 0.08);

    // Neck
    drawSphere(0.20, 0.77, 0, 0.16, 0.22, 0.15,
               0.80, 0.30, 0.08);

    // Head
    drawSphere(0.24, 0.98, 0, 0.17, 0.17, 0.16,
               0.80, 0.30, 0.08);

    // Red comb
    drawSphere(0.18, 1.16, 0, 0.06, 0.10, 0.07,
               0.85, 0.04, 0.04);

    drawSphere(0.27, 1.18, 0, 0.06, 0.10, 0.07,
               0.85, 0.04, 0.04);

    drawSphere(0.35, 1.13, 0, 0.05, 0.08, 0.06,
               0.85, 0.04, 0.04);

    // Wattles
    drawSphere(0.28, 0.83, 0.12, 0.045, 0.10, 0.04,
               0.85, 0.04, 0.04);

    // Beak
    drawCone(0.39, 0.96, 0.02,
             0.07, 0.13,
             1.0, 0.70, 0.05);

    // Eye
    drawSphere(0.30, 1.02, 0.14,
               0.025, 0.03, 0.02,
               0, 0, 0);

    // Wings
    drawSphere(-0.05, 0.55, 0.21,
               0.23, 0.15, 0.07,
               0.80, 0.35, 0.08);

    drawSphere(-0.05, 0.55, -0.21,
               0.23, 0.15, 0.07,
               0.80, 0.35, 0.08);

    // Tail feathers
    drawSphere(-0.32, 0.72, 0,
               0.10, 0.24, 0.08,
               0.10, 0.35, 0.12);

    drawSphere(-0.40, 0.80, 0.10,
               0.09, 0.23, 0.07,
               0.12, 0.42, 0.15);

    drawSphere(-0.40, 0.80, -0.10,
               0.09, 0.23, 0.07,
               0.12, 0.42, 0.15);

    // Legs
    drawCube(-0.10, 0.15, 0.07,
             0.05, 0.25, 0.05,
             0.95, 0.65, 0.05);

    drawCube(0.12, 0.15, -0.07,
             0.05, 0.25, 0.05,
             0.95, 0.65, 0.05);

    // Feet
    drawSphere(-0.05, 0.035, 0.07,
               0.13, 0.04, 0.08,
               0.95, 0.65, 0.05);

    drawSphere(0.17, 0.035, -0.07,
               0.13, 0.04, 0.08,
               0.95, 0.65, 0.05);

    glPopMatrix();
}
